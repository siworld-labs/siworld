pub(crate) mod tls_signer;

pub const VERSION: u16 = 1;
pub const DESCRIPTOR_BYTES: usize = 5459;
pub const PIN_BYTES: usize = 134;
const BODY_BYTES: usize = DESCRIPTOR_BYTES - 64 - 3309;
const SECRET_BYTES: usize = 198;
const IDENTITY_FILE: &str = "native-peer-identity.secret";
const MESSAGE_DOMAIN: &[u8] = b"siworld native peer identity descriptor v1\0";
const SIGNATURE_CONTEXT: &[u8] = b"siworld native peer identity v1";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    Storage,
    InvalidRecord,
    ContextMismatch,
    Signature,
    UnexpectedPeer,
    Entropy,
    UnsupportedPlatform,
}

/// Neither Clone nor secret serialization is implemented. The on-disk seeds
/// are private service credentials, independent of wallet and fund keys.
pub struct NativeIdentity {
    binding: Binding,
    ed25519: SigningKey,
    ml_dsa: MLDSA65SigningKey,
    ml_dsa_public: [u8; 1952],
}
impl std::fmt::Debug for NativeIdentity {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("NativeIdentity(REDACTED)")
    }
}
impl Drop for NativeIdentity {
    fn drop(&mut self) {
        // ed25519-dalek's zeroize feature erases its signing key on Drop.
        self.ml_dsa.as_mut_slice().zeroize();
    }
}
impl zeroize::ZeroizeOnDrop for NativeIdentity {}

impl NativeIdentity {
    fn from_seeds(binding: Binding, ed25519: &[u8; 32], ml_dsa: &[u8; 32]) -> Self {
        let pair = ml_dsa_65::generate_key_pair(*ml_dsa);
        Self {
            binding,
            ed25519: SigningKey::from_bytes(ed25519),
            ml_dsa: pair.signing_key,
            ml_dsa_public: *pair.verification_key.as_ref(),
        }
    }

    /// Explicit, write-once initialization into an existing private directory.
    /// A missing/corrupt record is never regenerated by load or service start.
    pub fn initialize(directory: &Path, binding: Binding) -> Result<Self, Error> {
        check_binding(&binding)?;
        let storage = Storage::open(directory)?;
        let mut ed25519 = Zeroizing::new([0; 32]);
        let mut ml_dsa = Zeroizing::new([0; 32]);
        getrandom::fill(ed25519.as_mut()).map_err(|_| Error::Entropy)?;
        getrandom::fill(ml_dsa.as_mut()).map_err(|_| Error::Entropy)?;
        let mut bytes = Zeroizing::new([0; SECRET_BYTES]);
        bytes[..4].copy_from_slice(b"SWIK");
        bytes[4..6].copy_from_slice(&VERSION.to_le_bytes());
        encode_binding(&binding, &mut bytes[6..102]);
        bytes[102..134].copy_from_slice(ed25519.as_ref());
        bytes[134..166].copy_from_slice(ml_dsa.as_ref());
        let checksum =
            blake3::derive_key("siworld native identity storage checksum v1", &bytes[..166]);
        bytes[166..].copy_from_slice(&checksum);
        storage.write_once(IDENTITY_FILE, bytes.as_ref())?;
        Ok(Self::from_seeds(binding, &ed25519, &ml_dsa))
    }

    pub fn load(directory: &Path, expected: &Binding) -> Result<Self, Error> {
        check_binding(expected)?;
        let bytes = Storage::open(directory)?.read_exact(IDENTITY_FILE, SECRET_BYTES)?;
        if &bytes[..4] != b"SWIK" || bytes[4..6] != VERSION.to_le_bytes() {
            return Err(Error::InvalidRecord);
        }
        let checksum =
            blake3::derive_key("siworld native identity storage checksum v1", &bytes[..166]);
        if bytes[166..] != checksum {
            return Err(Error::InvalidRecord);
        }
        decode_binding(&bytes[6..102], expected)?;
        let ed25519 = Zeroizing::new(
            bytes[102..134]
                .try_into()
                .map_err(|_| Error::InvalidRecord)?,
        );
        let ml_dsa = Zeroizing::new(
            bytes[134..166]
                .try_into()
                .map_err(|_| Error::InvalidRecord)?,
        );
        Ok(Self::from_seeds(*expected, &ed25519, &ml_dsa))
    }

    /// Export only public keys, their context binding and possession signatures.
    /// Fresh hedging changes the ML-DSA signature, not the public fingerprint.
    pub fn descriptor(&self) -> Result<Descriptor, Error> {
        let mut result = Descriptor {
            binding: self.binding,
            ed25519_public: self.ed25519.verifying_key().to_bytes(),
            ml_dsa_public: self.ml_dsa_public,
            ed25519_signature: [0; 64],
            ml_dsa_signature: [0; 3309],
        };
        let message = result.message();
        result.ed25519_signature = self.ed25519.sign(&message).to_bytes();
        let mut randomness = Zeroizing::new([0; 32]);
        getrandom::fill(randomness.as_mut()).map_err(|_| Error::Entropy)?;
        result.ml_dsa_signature =
            *ml_dsa_65::sign(&self.ml_dsa, &message, SIGNATURE_CONTEXT, *randomness)
                .map_err(|_| Error::Signature)?
                .as_ref();
        result.verify(&self.binding)?;
        Ok(result)
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Descriptor {
    binding: Binding,
    ed25519_public: [u8; 32],
    ml_dsa_public: [u8; 1952],
    ed25519_signature: [u8; 64],
    ml_dsa_signature: [u8; 3309],
}
impl Descriptor {
    fn body(&self) -> [u8; BODY_BYTES] {
        let mut bytes = [0; BODY_BYTES];
        bytes[..4].copy_from_slice(b"SWID");
        bytes[4..6].copy_from_slice(&VERSION.to_le_bytes());
        encode_binding(&self.binding, &mut bytes[6..102]);
        bytes[102..134].copy_from_slice(&self.ed25519_public);
        bytes[134..].copy_from_slice(&self.ml_dsa_public);
        bytes
    }
    fn message(&self) -> Vec<u8> {
        let mut message = Vec::with_capacity(MESSAGE_DOMAIN.len() + BODY_BYTES);
        message.extend_from_slice(MESSAGE_DOMAIN);
        message.extend_from_slice(&self.body());
        message
    }
    pub fn fingerprint(&self) -> Hash {
        blake3::derive_key("siworld native peer identity fingerprint v1", &self.body())
    }
    pub fn binding(&self) -> Binding {
        self.binding
    }
    pub fn ed25519_public(&self) -> &[u8; 32] {
        &self.ed25519_public
    }
    pub fn ml_dsa_public(&self) -> &[u8; 1952] {
        &self.ml_dsa_public
    }
    pub fn encode(&self) -> [u8; DESCRIPTOR_BYTES] {
        let mut bytes = [0; DESCRIPTOR_BYTES];
        bytes[..BODY_BYTES].copy_from_slice(&self.body());
        bytes[BODY_BYTES..BODY_BYTES + 64].copy_from_slice(&self.ed25519_signature);
        bytes[BODY_BYTES + 64..].copy_from_slice(&self.ml_dsa_signature);
        bytes
    }
    pub fn decode(bytes: &[u8], expected: &Binding) -> Result<Self, Error> {
        if bytes.len() != DESCRIPTOR_BYTES
            || &bytes[..4] != b"SWID"
            || bytes[4..6] != VERSION.to_le_bytes()
        {
            return Err(Error::InvalidRecord);
        }
        decode_binding(&bytes[6..102], expected)?;
        let result = Self {
            binding: *expected,
            ed25519_public: bytes[102..134]
                .try_into()
                .map_err(|_| Error::InvalidRecord)?,
            ml_dsa_public: bytes[134..BODY_BYTES]
                .try_into()
                .map_err(|_| Error::InvalidRecord)?,
            ed25519_signature: bytes[BODY_BYTES..BODY_BYTES + 64]
                .try_into()
                .map_err(|_| Error::InvalidRecord)?,
            ml_dsa_signature: bytes[BODY_BYTES + 64..]
                .try_into()
                .map_err(|_| Error::InvalidRecord)?,
        };
        result.verify(expected)?;
        Ok(result)
    }
    fn verify(&self, expected: &Binding) -> Result<(), Error> {
        check_binding(expected)?;
        if self.binding != *expected {
            return Err(Error::ContextMismatch);
        }
        if self.ed25519_public == [0; 32] || self.ml_dsa_public == [0; 1952] {
            return Err(Error::InvalidRecord);
        }
        let message = self.message();
        let ed25519 =
            VerifyingKey::from_bytes(&self.ed25519_public).map_err(|_| Error::Signature)?;
        ed25519
            .verify_strict(&message, &EdSignature::from_bytes(&self.ed25519_signature))
            .map_err(|_| Error::Signature)?;
        ml_dsa_65::verify(
            &MLDSA65VerificationKey::new(self.ml_dsa_public),
            &message,
            SIGNATURE_CONTEXT,
            &MLDSA65Signature::new(self.ml_dsa_signature),
        )
        .map_err(|_| Error::Signature)
    }
}

/// Construct only after authenticating the descriptor through an independent
/// trusted channel. Receiving a self-signed descriptor is not that step.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PeerPin {
    binding: Binding,
    fingerprint: Hash,
}
impl PeerPin {
    pub fn from_trusted_descriptor(
        descriptor: &Descriptor,
        expected: &Binding,
    ) -> Result<Self, Error> {
        descriptor.verify(expected)?;
        Ok(Self {
            binding: *expected,
            fingerprint: descriptor.fingerprint(),
        })
    }
    pub fn fingerprint(&self) -> Hash {
        self.fingerprint
    }
    pub fn verify(&self, descriptor: &Descriptor) -> Result<(), Error> {
        descriptor.verify(&self.binding)?;
        if descriptor.fingerprint() != self.fingerprint {
            return Err(Error::UnexpectedPeer);
        }
        Ok(())
    }
    pub fn encode(&self) -> [u8; PIN_BYTES] {
        let mut bytes = [0; PIN_BYTES];
        bytes[..4].copy_from_slice(b"SWIP");
        bytes[4..6].copy_from_slice(&VERSION.to_le_bytes());
        encode_binding(&self.binding, &mut bytes[6..102]);
        bytes[102..].copy_from_slice(&self.fingerprint);
        bytes
    }
    pub fn persist(&self, directory: &Path) -> Result<(), Error> {
        Storage::open(directory)?.write_once(&pin_filename(&self.fingerprint), &self.encode())
    }
    pub fn load(directory: &Path, fingerprint: Hash, expected: &Binding) -> Result<Self, Error> {
        check_binding(expected)?;
        if fingerprint == [0; 32] {
            return Err(Error::InvalidRecord);
        }
        let bytes = Storage::open(directory)?.read_exact(&pin_filename(&fingerprint), PIN_BYTES)?;
        if &bytes[..4] != b"SWIP" || bytes[4..6] != VERSION.to_le_bytes() {
            return Err(Error::InvalidRecord);
        }
        decode_binding(&bytes[6..102], expected)?;
        if bytes[102..] != fingerprint {
            return Err(Error::UnexpectedPeer);
        }
        Ok(Self {
            binding: *expected,
            fingerprint,
        })
    }
}

fn pin_filename(fingerprint: &Hash) -> String {
    format!("peer-{}.pin", crate::local::hex(fingerprint))
}
fn check_binding(binding: &Binding) -> Result<(), Error> {
    if binding.network == [0; 32] || binding.genesis == [0; 32] || binding.verifier == [0; 32] {
        return Err(Error::ContextMismatch);
    }
    Ok(())
}
fn encode_binding(binding: &Binding, bytes: &mut [u8]) {
    bytes[..32].copy_from_slice(&binding.network);
    bytes[32..64].copy_from_slice(&binding.genesis);
    bytes[64..96].copy_from_slice(&binding.verifier);
}
fn decode_binding(bytes: &[u8], expected: &Binding) -> Result<(), Error> {
    check_binding(expected)?;
    if bytes[..32] != expected.network
        || bytes[32..64] != expected.genesis
        || bytes[64..96] != expected.verifier
    {
        return Err(Error::ContextMismatch);
    }
    Ok(())
}

#[cfg(unix)]
use storage::Storage;
#[cfg(unix)]
mod storage {
    use super::*;
    use rustix::fd::OwnedFd;
    use rustix::fs::{self, AtFlags, FileType, Mode, OFlags};
    use std::fs::File;
    use std::io::{Read, Write};
    use std::path::Component;

    pub(super) struct Storage(OwnedFd);
    impl Storage {
        pub(super) fn open(path: &Path) -> Result<Self, Error> {
            let absolute = if path.is_absolute() {
                path.to_path_buf()
            } else {
                std::env::current_dir()
                    .map_err(|_| Error::Storage)?
                    .join(path)
            };
            let flags = OFlags::RDONLY | OFlags::DIRECTORY | OFlags::NOFOLLOW | OFlags::CLOEXEC;
            let mut directory = fs::open("/", flags, Mode::empty()).map_err(|_| Error::Storage)?;
            for component in absolute.components() {
                match component {
                    Component::RootDir | Component::CurDir => (),
                    Component::Normal(name) => {
                        directory = fs::openat(&directory, name, flags, Mode::empty())
                            .map_err(|_| Error::Storage)?;
                    }
                    _ => return Err(Error::Storage),
                }
            }
            let stat = fs::fstat(&directory).map_err(|_| Error::Storage)?;
            if FileType::from_raw_mode(stat.st_mode) != FileType::Directory
                || stat.st_uid != rustix::process::geteuid().as_raw()
                || stat.st_mode & 0o077 != 0
            {
                return Err(Error::Storage);
            }
            Ok(Self(directory))
        }
        pub(super) fn read_exact(
            &self,
            name: &str,
            size: usize,
        ) -> Result<Zeroizing<Vec<u8>>, Error> {
            let descriptor = fs::openat(
                &self.0,
                name,
                OFlags::RDONLY | OFlags::NOFOLLOW | OFlags::NONBLOCK | OFlags::CLOEXEC,
                Mode::empty(),
            )
            .map_err(|_| Error::Storage)?;
            let stat = fs::fstat(&descriptor).map_err(|_| Error::Storage)?;
            if FileType::from_raw_mode(stat.st_mode) != FileType::RegularFile
                || stat.st_uid != rustix::process::geteuid().as_raw()
                || stat.st_mode & 0o077 != 0
                || stat.st_nlink != 1
                || stat.st_size != size as i64
            {
                return Err(Error::Storage);
            }
            let mut file = File::from(descriptor);
            let mut bytes = Zeroizing::new(Vec::with_capacity(size + 1));
            (&mut file)
                .take((size + 1) as u64)
                .read_to_end(&mut bytes)
                .map_err(|_| Error::Storage)?;
            if bytes.len() != size {
                return Err(Error::Storage);
            }
            Ok(bytes)
        }
        pub(super) fn write_once(&self, name: &str, bytes: &[u8]) -> Result<(), Error> {
            let mut token = [0; 16];
            getrandom::fill(&mut token).map_err(|_| Error::Entropy)?;
            let temporary = format!(".native-identity-{}.tmp", crate::local::hex(&token));
            let descriptor = fs::openat(
                &self.0,
                temporary.as_str(),
                OFlags::WRONLY | OFlags::CREATE | OFlags::EXCL | OFlags::NOFOLLOW | OFlags::CLOEXEC,
                Mode::from_raw_mode(0o600),
            )
            .map_err(|_| Error::Storage)?;
            let owned = fs::fstat(&descriptor).map_err(|_| Error::Storage)?;
            let mut file = File::from(descriptor);
            let result = (|| {
                file.write_all(bytes)
                    .and_then(|_| file.sync_all())
                    .map_err(|_| Error::Storage)?;
                // linkat creates the final name only if absent. It never replaces
                // an existing key, symlink, directory, or concurrently won init.
                fs::linkat(&self.0, temporary.as_str(), &self.0, name, AtFlags::empty())
                    .map_err(|_| Error::Storage)?;
                Ok(())
            })();
            let current = fs::statat(&self.0, temporary.as_str(), AtFlags::SYMLINK_NOFOLLOW)
                .map_err(|_| Error::Storage)?;
            if current.st_dev != owned.st_dev || current.st_ino != owned.st_ino {
                return Err(Error::Storage);
            }
            fs::unlinkat(&self.0, temporary.as_str(), AtFlags::empty())
                .map_err(|_| Error::Storage)?;
            fs::fsync(&self.0).map_err(|_| Error::Storage)?;
            result
        }
    }
}

