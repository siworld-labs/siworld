//! Persisted, context-bound Ed25519 and ML-DSA-65 peer identities.
//!
//! A self-signed descriptor proves key possession, not trust, an authenticated
//! session, or transcript freshness. No transport capability is constructed.
use crate::p2p::Binding;
use crate::wire::Hash;
use ed25519_dalek::{Signature as EdSignature, Signer, SigningKey, VerifyingKey};
use libcrux_ml_dsa::ml_dsa_65::{
    self, MLDSA65Signature, MLDSA65SigningKey, MLDSA65VerificationKey,
};
use std::path::Path;
use zeroize::{Zeroize, Zeroizing};

// Reserved for a reviewed transport provider; never admits a channel itself.
#[allow(dead_code)]
pub(crate) mod handshake_auth;
#[cfg(feature = "hybrid-tls-candidate")]
